/**
 * Copies the constants of @prism-code/spec into src/vendor/spec/, byte for byte
 * below a header that names the origin.
 *
 * Why copy instead of depend: prism-code has no dependencies, and `prism.errors`
 * sits below every other module, so it cannot reach the copy inside
 * src/vendor/verify.mjs (#440). The two files are data and import only each other.
 *
 * `node scripts/vendor-spec.mjs` writes the files. `--check` fails when they
 * differ from what sdk/npm/spec would produce today.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (relative) => fileURLToPath(new URL(relative, import.meta.url));
const FILES = ['constants.mjs', 'assurance-levels.mjs'];

const expected = (name) =>
  `// GENERATED by scripts/vendor-spec.mjs from sdk/npm/spec/${name}. Do not edit; run \`node scripts/vendor-spec.mjs\`.\n\n` +
  readFileSync(here(`../../spec/${name}`), 'utf8').replace(/\r\n/g, '\n');

if (process.argv.includes('--check')) {
  for (const name of FILES) {
    let actual = null;
    try {
      actual = readFileSync(here(`../src/vendor/spec/${name}`), 'utf8').replace(/\r\n/g, '\n');
    } catch {
      // reported below
    }
    if (actual !== expected(name)) {
      console.error(`src/vendor/spec/${name} is not what sdk/npm/spec/${name} produces today. Run: node scripts/vendor-spec.mjs`);
      process.exit(1);
    }
  }
  console.log('vendored spec is current');
} else {
  mkdirSync(here('../src/vendor/spec'), { recursive: true });
  for (const name of FILES) writeFileSync(here(`../src/vendor/spec/${name}`), expected(name));
  console.log('wrote src/vendor/spec');
}
