/**
 * The files that make a guided-journey app an instance of UOR-Foundation/template,
 * so it has the template's frame, page, gate and Pages URL.
 *
 * A template instance keeps its app in `app/`, and its gate (`just vv`) holds
 * every claim three ways: a row in `model/ids.toml`, a scenario in
 * `features/suites/`, and a test whose name ends in the row's ID. Each stated
 * property becomes one such claim, `XX-01`, `XX-02`, ..., where `XX` is two
 * letters from the app's name: the meta-gate reads exactly two letters and two
 * digits off a test name. The test pins what the theorem is about, the
 * condition no request may meet and the statement that none does, so a
 * weakened property that still verifies fails the gate. The page reads
 * `site/app.json`; its images are drawn from it by the template's Pages run.
 *
 * Everything here is a pure function of the spec, the template's own files and
 * what the build learned, so the same inputs write the same bytes.
 */
import { createHash } from 'node:crypto';
import { describeConditions } from './spec.mjs';
import { names, proofDeclarations } from './render.mjs';

/** The template's example app, which a new instance replaces. */
export const TEMPLATE_EXAMPLE = Object.freeze(['app/src/Contract.lex.tex', 'crates/conformance/tests/contract.rs', 'features/suites/contract.feature']);

/** The Gherkin suite, the feature file's name and every test name's start: the spec's name with underscores. */
export const suiteOf = (spec) => spec.name.replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'app';

/**
 * Two letters for the app's IDs: the initials of a name of two words or more,
 * else its first two letters. `CM` is the meta-gate's own rule name, so it is
 * never taken.
 */
export function idPrefix(spec) {
  const words = spec.name.split(/[^a-z]+/).filter(Boolean);
  let prefix = words.length >= 2 ? `${words[0][0]}${words[1][0]}` : (words[0] ?? 'ap').padEnd(2, 'p').slice(0, 2);
  prefix = prefix.toUpperCase();
  return prefix === 'CM' ? 'CN' : prefix;
}

/** One claim per stated property: its ID, statement, the declarations it is about and its test. */
export function claims(spec) {
  const n = names(spec);
  const prefix = idPrefix(spec);
  const suite = suiteOf(spec);
  const proofs = proofDeclarations(spec, n);
  return spec.properties.map((p, i) => {
    const id = `${prefix}-${String(i + 1).padStart(2, '0')}`;
    const { breaks, theorem } = n.properties[p.id];
    return {
      id,
      statement: `The app ${p.kind} answers ${p.then} when ${describeConditions(p.when)}`,
      breaks,
      theorem,
      condition: proofs.find((d) => d.name === breaks).body,
      test: `${suite}_${id.toLowerCase().replace('-', '_')}`,
    };
  });
}

const tomlString = (text) => JSON.stringify(text);

/** `model/ids.toml`: the template's header comment kept, every row replaced by the app's claims. */
export function idsToml(spec, current) {
  const head = current.slice(0, current.indexOf('[[id]]') < 0 ? current.length : current.indexOf('[[id]]')).replace(/\n*$/, '\n\n');
  const rows = claims(spec).map((c) => `[[id]]\nid = "${c.id}"\nlevel = "build"\nsuite = "${suiteOf(spec)}"\nstatement = ${tomlString(c.statement)}\n`);
  return `${head}${rows.join('\n')}`;
}

/** `features/suites/<suite>.feature`: one scenario per claim, tagged with its ID and level. */
export function featureText(spec) {
  const n = names(spec);
  const lines = [`Feature: ${suiteOf(spec)}`, '', `  This repository's Prism application, in app/, generated by prism-code from its`, `  spec: ${spec.purpose.replace(/\s+/g, ' ').trim()}`];
  for (const c of claims(spec)) {
    lines.push('', `  @${c.id} @build`, `  Scenario: ${c.statement}`, `    Given the model in app/src/${n.module}.lex.tex`, `    When the Lean kernel checks ${c.theorem} during prismpm verify`, `    Then no request meets ${c.breaks}`);
  }
  return `${lines.join('\n')}\n`;
}

const rustString = (text) => `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/**
 * `crates/conformance/tests/<suite>.rs`: one test per claim, in the layout
 * `cargo fmt` gives it, since the gate runs `cargo fmt --check`.
 */
export function rustTestText(spec) {
  const n = names(spec);
  const suite = suiteOf(spec);
  const tests = claims(spec).map((c) => [
    '',
    `/// \`${c.id}\`: ${c.statement}`,
    '#[test]',
    `fn ${c.test}() {`,
    '    pinned(',
    `        ${rustString(c.breaks)},`,
    `        ${rustString(`body: ${c.condition}`)},`,
    `        ${rustString(c.theorem)},`,
    '    );',
    '}',
  ].join('\n'));
  return `${[
    `//! The \`${suite}\` suite: one test per scenario in \`features/suites/${suite}.feature\`.`,
    '//!',
    '//! Generated by prism-code from the app\'s spec. The proofs are checked by the',
    '//! Lean kernel when `just vv` runs `prismpm verify` on `app/`. What these tests',
    '//! hold fixed is the claim each proof is about: the condition no request may',
    '//! meet, and the theorem that states none does. A weakened condition would',
    '//! still verify, and would no longer be the claim its row makes.',
    '',
    'use std::path::PathBuf;',
    '',
    'fn root() -> PathBuf {',
    '    PathBuf::from(env!("CARGO_MANIFEST_DIR"))',
    '        .ancestors()',
    '        .nth(2)',
    '        .expect("crates/conformance is two below the root")',
    '        .to_path_buf()',
    '}',
    '',
    '/// The body of the top-level declaration named `name`, up to its closing brace.',
    'fn declaration<\'a>(model: &\'a str, name: &str) -> &\'a str {',
    '    let start = model',
    '        .find(&format!("\\n  name: {name},\\n"))',
    '        .unwrap_or_else(|| panic!("{name} is not declared"));',
    '    let end = model[start..]',
    '        .find("\\n}\\n")',
    '        .unwrap_or_else(|| panic!("{name} is not closed"));',
    '    &model[start..start + end]',
    '}',
    '',
    '/// The condition no request may meet, and the theorem that says none does.',
    'fn pinned(breaks: &str, condition: &str, theorem: &str) {',
    `    let path = root().join(${rustString(`app/src/${n.proofs}.lex.tex`)});`,
    '    let model = std::fs::read_to_string(path).expect("the proofs module");',
    '    let found = declaration(&model, breaks);',
    '    assert!(',
    '        found.contains(condition),',
    '        "the condition of {breaks} changed:\\n{found}"',
    '    );',
    '    let holds = declaration(&model, theorem);',
    '    let statement = format!("statement: (({breaks} request) = false),");',
    '    assert!(',
    '        holds.contains(&statement),',
    '        "{theorem} must state that no request meets {breaks}:\\n{holds}"',
    '    );',
    '}',
  ].join('\n')}\n${tests.join('\n')}\n`;
}

/**
 * `CONFORMANCE.md` as `cargo xtask check-model --write` renders it: the
 * template's text kept, the suite sections between the honesty levels and
 * "Cited authorities" replaced by the app's.
 */
export function conformanceText(spec, current) {
  const start = current.indexOf('\n## ');
  const end = current.indexOf('\n## Cited authorities');
  if (start < 0 || end < 0) throw new Error('CONFORMANCE.md has no suite sections to replace');
  const rows = claims(spec).map((c) => `| \`${c.id}\` | \`build\` | ${c.statement.replace(/\|/g, '\\|').trim()} |`);
  const section = rows.length ? `\n## ${suiteOf(spec)}\n\n| ID | Level | Statement |\n| --- | --- | --- |\n${rows.join('\n')}\n` : '';
  return `${current.slice(0, start)}${section}${current.slice(end)}`;
}

/** The text of the rules, for the page's proposition. */
function rulesText(spec) {
  const lines = spec.rules.map((r) => `${describeConditions(r.when)} → ${r.then}`);
  return [`judge request :=`, ...lines.map((l) => `  ${l}`), `  otherwise → ${spec.otherwise}`].join('\n');
}

/**
 * `site/app.json`: the template's page description, rewritten for this app.
 * `repository` is `owner/name`; `attestation` the hosted proof's ID, or null.
 */
export function appJson(spec, current, { repository, attestation = null }) {
  const [owner, repo] = repository.split('/');
  const url = `https://github.com/${repository}`;
  const live = `https://${owner.toLowerCase()}.github.io/${repo}/`;
  const list = (items) => items.join(', ').replace(/, ([^,]*)$/, ' or $1');
  const all = claims(spec);
  const example = spec.examples[0]?.request ?? spec.fields.map((f) => (f.kind === 'choice' ? f.values[0] : String(f.min ?? 1))).join(' ');
  const app = JSON.parse(current);
  return `${JSON.stringify(
    {
      ...app,
      name: spec.title,
      shortName: spec.title.split(/\s+/)[0].slice(0, 12),
      live,
      purpose: `${spec.purpose.replace(/\.$/, '')}. Send ${list(spec.fields.map((f) => f.name))}, separated by spaces; it answers ${list(spec.outcomes)}, and invalid request for anything else.`,
      inputLabel: `Request: ${spec.fields.map((f) => f.name).join(' ')}`,
      placeholder: example,
      submitLabel: 'Decide',
      outputLabel: 'Answer',
      answers: { positive: spec.outcomes.slice(0, 1), negative: spec.outcomes.slice(1), refusal: 'invalid request' },
      claim: all.length ? all.map((c) => `${c.id}: ${c.statement.replace(/^The app/, 'the app')}.`).join(' ') : 'No property is stated, so nothing about the rules is proved; the examples are tested.',
      proposition: { name: 'judge', text: rulesText(spec), plain: spec.purpose },
      theorems: all.map((c) => ({ name: c.theorem, statement: `no request meets ${c.breaks}: ${c.statement.replace(/^The app/, 'the app')}`, how: 'Proved by linear arithmetic, checked by the Lean kernel on the UOR MCP server and again by prismpm verify in CI', where: `app/src/${names(spec).proofs}.lex.tex` })),
      pinned: all.map((c) => ({ name: c.test, what: `${c.id}'s condition and the theorem that no request meets it. A string-matching test, not a theorem: a planted defect fails it.`, where: `crates/conformance/tests/${suiteOf(spec)}.rs` })),
      attestations: {
        proof: { id: attestation ?? 'not recorded: the proof ran in the SDK image, not on the UOR MCP server', url: `${url}/actions/workflows/bootstrap.yml` },
        build: { id: 'printed by prismpm verify in every pages run', url: `${url}/actions/workflows/pages.yml` },
      },
      repository: url,
      report: `${url}/blob/main/TEMPLATE-VERIFICATION.md`,
    },
    null,
    2,
  )}\n`;
}

/**
 * `app/lexlean.lock` for the app's project files. The lock binds the project
 * config and the Lean workspace files by SHA-256, and the packages, which a
 * template instance and the journey's scaffold share, so only those four
 * digests change. `files` maps each path under `app/` to its bytes.
 */
export function lexleanLockText(current, files) {
  const sha = (path) => {
    if (!Object.hasOwn(files, path)) throw new Error(`no ${path} to lock`);
    return createHash('sha256').update(files[path]).digest('hex');
  };
  let lock = current.replace(/^project_config_sha256 = "[0-9a-f]{64}"$/m, `project_config_sha256 = "${sha('lexlean.toml')}"`);
  for (const path of ['lake-manifest.json', 'lakefile.toml', 'lean-toolchain']) {
    const entry = new RegExp(`(\\[\\[workspace_file\\]\\]\\npath = "${path.replace(/\./g, '\\.')}"\\nsha256 = ")[0-9a-f]{64}"`);
    if (!entry.test(lock)) throw new Error(`lexlean.lock has no workspace_file ${path}`);
    lock = lock.replace(entry, `$1${sha(path)}"`);
  }
  return lock;
}

/** The live URL GitHub Pages gives a repository. */
export const liveUrl = (repository) => {
  const [owner, repo] = repository.split('/');
  return `https://${owner.toLowerCase()}.github.io/${repo}/`;
};
