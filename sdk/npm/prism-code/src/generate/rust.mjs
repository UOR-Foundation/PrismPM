/**
 * The Rust writer of `prism-code generate` (issue #289): turns the code model
 * into a small crate with no dependencies and no `unsafe`. It is written to
 * read as if a person wrote it: one module for the world, one for the
 * application's client, named constants, and doc comments taken from the WIT
 * world and the model.
 *
 * The crate does not pick a WebAssembly engine. `world::Guest` is the world's
 * exports as a trait, which a host implements over the engine it already uses,
 * and `world::dispatch` is the host protocol over that trait. The client takes
 * any `FnMut(&[u8]) -> Result<Vec<u8>, E>`, so it works the same over a guest,
 * a remote host or a recorded history.
 *
 * `write(model)` returns `[path, text]` pairs, LF line ends, in a fixed order.
 */
import { fail } from '../errors.mjs';

const HEADER = (from) => `// Generated by \`prism-code generate\` from ${from}.\n// Do not edit: run \`prism-code generate\` again.\n`;

const lines = (...parts) => `${parts.flat(Infinity).filter((p) => p !== null).join('\n')}\n`;
const doc = (indent, text, marker = '///') => (text.length === 0 ? null : text.map((t) => `${indent}${marker} ${t}`.trimEnd()).join('\n'));
const string = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;

/** `holo-run` and `holo_run` read as `holo_run`; `division-by-zero` as `DivisionByZero`. */
const snake = (name) => name.replace(/-/g, '_').replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const pascal = (name) => name.split(/[-_]/).filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join('');

const KEYWORDS = new Set(['as', 'break', 'const', 'continue', 'crate', 'else', 'enum', 'extern', 'false', 'fn', 'for', 'if', 'impl', 'in', 'let', 'loop', 'match', 'mod', 'move', 'mut', 'pub', 'ref', 'return', 'self', 'Self', 'static', 'struct', 'super', 'trait', 'true', 'type', 'unsafe', 'use', 'where', 'while', 'async', 'await', 'dyn', 'abstract', 'become', 'box', 'do', 'final', 'macro', 'override', 'priv', 'typeof', 'unsized', 'virtual', 'yield', 'try', 'gen']);
const ident = (name) => {
  if (!/^[a-z_][a-z0-9_]*$/.test(name)) fail('generate.model', `${JSON.stringify(name)} is not a name the rust writer can bind`);
  return KEYWORDS.has(name) ? `r#${name}` : name;
};

/** How each scalar WIT type reads in Rust. */
const TYPES = Object.freeze({ bool: 'bool', u8: 'u8', u16: 'u16', u32: 'u32', u64: 'u64', s8: 'i8', s16: 'i16', s32: 'i32', s64: 'i64', f32: 'f32', f64: 'f64', char: 'char' });
const rustType = (type) => TYPES[type] ?? fail('generate.world', `the rust writer has no type for WIT ${type}`);

/**
 * The host side of each world, beyond what WIT can say: how a request reaches
 * the guest and how its response comes back. The core-wasm world states it in
 * its file's header comment.
 */
const PROTOCOLS = Object.freeze({
  'hologram:guest/core-wasm@1': [
    '/// Why a request did not come back from the guest.',
    '#[derive(Debug)]',
    'pub enum DispatchError<E> {',
    '    /// The request is longer than a guest can address.',
    '    TooLong(usize),',
    '    /// A call into the guest failed, as the engine reported it.',
    '    Guest(E),',
    '}',
    '',
    'impl<E: fmt::Display> fmt::Display for DispatchError<E> {',
    '    fn fmt(&self, f: &mut fmt::Formatter<\'_>) -> fmt::Result {',
    '        match self {',
    '            Self::TooLong(length) => write!(f, "a request of {length} bytes is too long"),',
    '            Self::Guest(error) => write!(f, "the guest failed: {error}"),',
    '        }',
    '    }',
    '}',
    '',
    'impl<E: fmt::Debug + fmt::Display> std::error::Error for DispatchError<E> {}',
    '',
    '/// Why [`dispatch`] failed for a guest `G`.',
    'pub type Failure<G> = DispatchError<<G as Guest>::Error>;',
    '',
    '/// Send one request to a fresh instance of the guest and return a copy of its response.',
    '/// The guest allocator never frees, so give every request its own instance.',
    'pub fn dispatch<G: Guest>(guest: &mut G, request: &[u8]) -> Result<Vec<u8>, Failure<G>> {',
    '    let length = u32::try_from(request.len()).map_err(|_| DispatchError::TooLong(request.len()))?;',
    '    let failed = DispatchError::Guest;',
    '    let offset = guest.holo_alloc(length).map_err(failed)?;',
    '    guest.write_memory(offset, request).map_err(failed)?;',
    '    let packed = guest.holo_run(offset, length).map_err(failed)?;',
    '    // The response location is packed as `offset << 32 | length`.',
    '    let at = (packed >> 32) as u32;',
    '    let size = (packed & 0xffff_ffff) as u32;',
    '    guest.read_memory(at, size).map_err(failed)',
    '}',
  ],
});

function worldFile(world) {
  const protocol = PROTOCOLS[world.contract] ?? fail('generate.world', `the rust writer has no host protocol for ${world.contract}`);
  if (world.imports.length !== 0) fail('generate.world', `the rust writer binds import-free worlds; ${world.contract} has imports`);
  const from = `the WIT world ${world.contract} (${world.file})`;
  const names = [...world.exports.map((f) => f.name), world.memory].sort();
  const methods = world.exports.map((f) => [
    doc('    ', f.docs),
    `    fn ${ident(f.name)}(&mut self${f.params.map((p) => `, ${ident(snake(p.name))}: ${rustType(p.type)}`).join('')}) -> Result<${f.result ? rustType(f.result.type) : '()'}, Self::Error>;`,
    '',
  ]);
  return lines(
    HEADER(from),
    `//! The world ${world.contract}: its identity, its exports, and how a host sends it a request.`,
    '',
    'use core::fmt;',
    '',
    'pub use crate::Identity;',
    '',
    '/// The world these bindings were generated from. It equals `inputs.world` in prismpm.lock.',
    'pub const WORLD: Identity = Identity {',
    `    name: ${string(world.contract)},`,
    `    blake3: ${string(world.digest.blake3)},`,
    `    sha256: ${string(world.digest.sha256)},`,
    '};',
    '',
    '/// Every export the world requires, sorted. A guest that offers any other is not of this world.',
    `pub const EXPORTS: [&str; ${names.length}] = [${names.map(string).join(', ')}];`,
    '',
    `/// A guest of ${world.contract}, instantiated by the host's WebAssembly engine.`,
    '///',
    `/// The guest imports nothing. Implement this over the engine's instance: each export, and \`${world.memory}\` as a read and a write.`,
    'pub trait Guest {',
    '    /// What the engine reports when a call into the guest fails, such as a trap.',
    '    type Error;',
    '',
    methods.flat(),
    `    /// Copy \`bytes\` into the guest's \`${world.memory}\` at \`offset\`.`,
    '    fn write_memory(&mut self, offset: u32, bytes: &[u8]) -> Result<(), Self::Error>;',
    '',
    `    /// Copy \`length\` bytes out of the guest's \`${world.memory}\` at \`offset\`. Fails when they are outside it.`,
    '    fn read_memory(&mut self, offset: u32, length: u32) -> Result<Vec<u8>, Self::Error>;',
    '}',
    '',
    protocol,
  );
}

/** The widest line rustfmt keeps whole, so the generated files are already formatted. */
const WIDTH = 100;

/** A match arm, wrapped in a block as rustfmt does when it does not fit on one line. */
const arm = (indent, pattern, value) => {
  const line = `${indent}${pattern} => ${value},`;
  return line.length <= WIDTH ? line : [`${indent}${pattern} => {`, `${indent}    ${value}`, `${indent}}`];
};

/** A function signature, one parameter a line when it does not fit on one, as rustfmt does. */
const signature = (indent, head, params, result) => {
  const line = `${indent}${head}(${params.join(', ')}) -> ${result} {`;
  return line.length <= WIDTH ? line : [`${indent}${head}(`, params.map((p) => `${indent}    ${p},`), `${indent}) -> ${result} {`];
};

/** An array constant, one element a line when its elements are wider than rustfmt's array width. */
const array = (indent, head, items) => {
  const inline = items.join(', ');
  const line = `${indent}${head} = [${inline}];`;
  return line.length <= WIDTH && inline.length <= WIDTH * 0.6 ? line : [`${indent}${head} = [`, items.map((i) => `${indent}    ${i},`), `${indent}];`];
};

function operationsFile(application) {
  const api = application.interface;
  const { type, errorType, operationType } = { type: application.type, ...api };
  const codeType = `${errorType}Code`;
  const from = `${application.name}'s model (${application.schema}, blake3:${application.model.blake3})`;
  const fallback = {
    'unsupported-version': `${application.name} does not answer request version ${api.version}.`,
    'unknown-operation': `${application.name} does not know this operation.`,
  };
  const variants = api.operations.map((o) => ({ ...o, variant: pascal(o.name), fn: ident(snake(o.name)) }));
  const errors = api.errors.map((e) => ({ ...e, variant: pascal(e.code), text: e.message ?? fallback[e.code] }));
  const method = ident(snake(api.method));
  const reserved = new Set(['new', method, 'dispatch', 'read']);
  for (const o of variants) if (reserved.has(o.fn)) fail('generate.model', `operation ${o.name} collides with the method ${o.fn}`);
  if (!errors.some((e) => e.code === 'unsupported-version')) fail('generate.model', `${application.name}'s model has no unsupported-version error`);
  const result = `Result<i64, ${errorType}<E>>`;
  const description = [`A client for ${application.name}.`, ...(application.description ? ['', application.description] : [])];
  return lines(
    HEADER(from),
    `//! The client of ${application.name}: one method per operation, over any dispatch function.`,
    '',
    'use core::fmt;',
    '',
    'pub use crate::Identity;',
    '',
    '/// The model this client was generated from. It equals `inputs.model` in prismpm.lock.',
    'pub const MODEL: Identity = Identity {',
    `    name: ${string(application.name)},`,
    `    blake3: ${string(application.model.blake3)},`,
    `    sha256: ${string(application.model.sha256)},`,
    '};',
    '',
    `const APPLICATION: &str = ${string(application.name)};`,
    `const VERSION: &str = ${string(api.version)};`,
    '',
    `/// An operation ${application.name} accepts.`,
    '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]',
    `pub enum ${operationType} {`,
    variants.map((o) => [`    /// ${o.label}.`, `    ${o.variant},`]).flat(),
    '}',
    '',
    `impl ${operationType} {`,
    `    /// Every operation ${application.name} accepts.`,
    array('    ', `pub const ALL: [Self; ${variants.length}]`, variants.map((o) => `Self::${o.variant}`)),
    '',
    '    /// The name the guest reads in a request.',
    '    pub const fn name(self) -> &\'static str {',
    '        match self {',
    variants.map((o) => arm('            ', `Self::${o.variant}`, string(o.name))),
    '        }',
    '    }',
    '}',
    '',
    `/// An answer with which ${application.name} refuses a request.`,
    '#[derive(Clone, Debug, PartialEq, Eq, Hash)]',
    `pub enum ${codeType} {`,
    errors.map((e) => [`    /// \`${e.code}\`: ${e.text}`, `    ${e.variant},`]).flat(),
    '    /// An answer this client was not generated with.',
    '    Other(String),',
    '}',
    '',
    `impl ${codeType} {`,
    '    /// The code as the guest wrote it.',
    '    pub fn code(&self) -> &str {',
    '        match self {',
    errors.map((e) => arm('            ', `Self::${e.variant}`, string(e.code))),
    '            Self::Other(code) => code,',
    '        }',
    '    }',
    '',
    '    /// What the model says this answer means, for a person.',
    '    pub fn message(&self) -> &str {',
    '        match self {',
    errors.map((e) => arm('            ', `Self::${e.variant}`, string(e.text))),
    arm('            ', 'Self::Other(_)', string(`${application.name} refused the request.`)),
    '        }',
    '    }',
    '',
    '    fn from_code(code: &str) -> Self {',
    '        match code {',
    errors.map((e) => arm('            ', string(e.code), `Self::${e.variant}`)),
    '            other => Self::Other(other.to_string()),',
    '        }',
    '    }',
    '}',
    '',
    `/// Why a call to ${application.name} gave no result.`,
    '#[derive(Debug)]',
    `pub enum ${errorType}<E> {`,
    `    /// ${application.name} refused the request, for example on overflow.`,
    `    Refused(${codeType}),`,
    '    /// The dispatch function failed before an answer came back.',
    '    Dispatch(E),',
    '    /// The answer is not one this client can read.',
    '    Response(String),',
    '}',
    '',
    `impl<E: fmt::Display> fmt::Display for ${errorType}<E> {`,
    '    fn fmt(&self, f: &mut fmt::Formatter<\'_>) -> fmt::Result {',
    '        match self {',
    '            Self::Refused(code) => write!(f, "{} ({})", code.message(), code.code()),',
    '            Self::Dispatch(error) => write!(f, "the request did not reach {APPLICATION}: {error}"),',
    '            Self::Response(why) => write!(f, "{APPLICATION} sent an unreadable answer: {why}"),',
    '        }',
    '    }',
    '}',
    '',
    `impl<E: fmt::Debug + fmt::Display> std::error::Error for ${errorType}<E> {}`,
    '',
    doc('', description),
    '///',
    '/// `dispatch` sends request bytes to the guest and returns its response bytes, for',
    '/// example `|request| crate::world::dispatch(&mut fresh_instance(), request)`.',
    `pub struct ${type}<D> {`,
    '    dispatch: D,',
    '}',
    '',
    `impl<D, E> ${type}<D>`,
    'where',
    '    D: FnMut(&[u8]) -> Result<Vec<u8>, E>,',
    '{',
    '    /// A client over this dispatch function.',
    '    pub fn new(dispatch: D) -> Self {',
    `        ${type} { dispatch }`,
    '    }',
    variants.map((o) => [
      '',
      `    /// ${o.label}: \`${method}(${operationType}::${o.variant}, left, right)\`.`,
      signature('    ', `pub fn ${o.fn}`, ['&mut self', 'left: i64', 'right: i64'], result),
      `        self.${method}(${operationType}::${o.variant}, left, right)`,
      '    }',
    ]).flat(),
    '',
    `    /// Apply \`operation\` to two signed 64-bit integers.`,
    `    ///`,
    `    /// A refusal by ${application.name} is \`${errorType}::Refused\`.`,
    signature('    ', `pub fn ${method}`, ['&mut self', `operation: ${operationType}`, 'left: i64', 'right: i64'], result),
    '        let request = format!("{VERSION}\\t{}\\t{left}\\t{right}", operation.name());',
    `        let response = (self.dispatch)(request.as_bytes()).map_err(${errorType}::Dispatch)?;`,
    '        read(&response)',
    '    }',
    '}',
    '',
    '/// Read a response: the request version, then `ok` and a value or `error` and a code.',
    signature('', 'fn read<E>', ['response: &[u8]'], result),
    // Sorted by their first segment, as rustfmt orders imports.
    [[codeType, `    use ${codeType} as Code;`], [errorType, `    use ${errorType}::{Refused, Response};`]]
      .sort(([x], [y]) => (x < y ? -1 : 1))
      .map(([, line]) => line),
    '    let Ok(text) = core::str::from_utf8(response) else {',
    '        return Err(Response("it is not UTF-8".to_string()));',
    '    };',
    '    let mut fields = text.split(\'\\t\');',
    '    let (version, status, value) = (fields.next(), fields.next(), fields.next());',
    '    if fields.next().is_some() {',
    '        return Err(Response(format!("{text:?} has more than three fields")));',
    '    }',
    '    if version != Some(VERSION) {',
    '        return Err(Refused(Code::UnsupportedVersion));',
    '    }',
    '    match (status, value) {',
    '        (Some("ok"), Some(value)) => value',
    '            .parse()',
    '            .map_err(|_| Response(format!("{value:?} is not a signed 64-bit integer"))),',
    '        (Some("error"), Some(code)) => Err(Refused(Code::from_code(code))),',
    '        _ => Err(Response(format!("{text:?} is neither ok nor error"))),',
    '    }',
    '}',
  );
}

function bytesFile(application) {
  const { type } = application;
  const from = `${application.name}'s model (${application.schema}, blake3:${application.model.blake3})`;
  const description = [`A client for ${application.name}, over request and response bytes.`, ...(application.description ? ['', application.description] : [])];
  return lines(
    HEADER(from),
    `//! The client of ${application.name}, over request and response bytes.`,
    '',
    'pub use crate::Identity;',
    '',
    '/// The model this client was generated from. It equals `inputs.model` in prismpm.lock.',
    'pub const MODEL: Identity = Identity {',
    `    name: ${string(application.name)},`,
    `    blake3: ${string(application.model.blake3)},`,
    `    sha256: ${string(application.model.sha256)},`,
    '};',
    '',
    doc('', description),
    '///',
    `/// ${application.name}'s model describes no typed operations, so the client sends bytes.`,
    `pub struct ${type}<D> {`,
    '    dispatch: D,',
    '}',
    '',
    `impl<D, E> ${type}<D>`,
    'where',
    '    D: FnMut(&[u8]) -> Result<Vec<u8>, E>,',
    '{',
    '    /// A client over this dispatch function.',
    '    pub fn new(dispatch: D) -> Self {',
    `        ${type} { dispatch }`,
    '    }',
    '',
    '    /// Send one request and return the response bytes.',
    '    pub fn invoke(&mut self, request: &[u8]) -> Result<Vec<u8>, E> {',
    '        (self.dispatch)(request)',
    '    }',
    '}',
  );
}

function crateFiles(model, module) {
  const { application, world } = model;
  const crate = `${application.file}-client`;
  const description = `A client for ${application.name}, generated by prism-code generate.`;
  const cargo = lines(
    `# Generated by \`prism-code generate\` from ${application.name}'s model and the WIT world ${world.contract}.`,
    '# Do not edit: run `prism-code generate` again.',
    '[package]',
    `name = ${string(crate)}`,
    'version = "0.1.0"',
    'edition = "2021"',
    `description = ${string(description)}`,
    'publish = false',
    '',
    '[lib]',
    'path = "lib.rs"',
    '',
    '[dependencies]',
  );
  const lib = lines(
    HEADER(`${application.name}'s model and the WIT world ${world.contract}`),
    `//! ${description}`,
    ...(application.description ? ['//!', `//! ${application.description}`] : []),
    '//!',
    `//! [\`world\`] is the world ${world.contract}: implement [\`world::Guest\`] over your WebAssembly engine,`,
    `//! and [\`world::dispatch\`] sends it a request. [\`${module}\`] is the client of ${application.name}.`,
    '',
    '#![forbid(unsafe_code)]',
    '',
    [`pub mod ${module};`, 'pub mod world;'].sort(),
    '',
    `pub use ${module}::*;`,
    '',
    '/// What a set of bindings was generated from: a name and both digests, as prismpm.lock records them.',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub struct Identity {',
    '    /// The world\'s contract, or the application\'s name.',
    '    pub name: &\'static str,',
    '    /// The BLAKE3 digest, lowercase hex.',
    '    pub blake3: &\'static str,',
    '    /// The SHA-256 digest, lowercase hex.',
    '    pub sha256: &\'static str,',
    '}',
  );
  return [
    ['Cargo.toml', cargo],
    ['lib.rs', lib],
  ];
}

/** The files of the Rust bindings: the crate, the world, then the application's client. */
export function write(model) {
  const module = ident(snake(model.application.file));
  if (module === 'world') fail('generate.model', 'an application named world collides with the world module');
  const client = model.application.interface.kind === 'operations' ? operationsFile(model.application) : bytesFile(model.application);
  return [...crateFiles(model, module), ['world.rs', worldFile(model.world)], [`${module}.rs`, client]];
}
