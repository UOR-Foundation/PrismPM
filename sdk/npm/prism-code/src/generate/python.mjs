/**
 * The Python writer of `prism-code generate` (issue #289): turns the code
 * model into a package that imports only the standard library (Python 3.9 and
 * later). It is written to read as if a person wrote it: one module for the
 * world, one for the application's client, named constants, type hints, and
 * docstrings taken from the WIT world and the model.
 *
 * The package does not pick a WebAssembly engine. `world.Guest` is the
 * world's exports as a protocol, which a host implements over the engine it
 * already uses, and `world.dispatch` is the host protocol over it. The client
 * takes any `Callable[[bytes], bytes]`, so it works the same over a guest, a
 * remote host or a recorded history.
 *
 * `write(model)` returns `[path, text]` pairs, LF line ends, in a fixed order.
 * The output directory is the package: name it as you will import it.
 */
import { fail } from '../errors.mjs';

const HEADER = (from) => `# Generated by \`prism-code generate\` from ${from}.\n# Do not edit: run \`prism-code generate\` again.\n`;

const lines = (...parts) => `${parts.flat(Infinity).filter((p) => p !== null).join('\n')}\n`;
const string = (s) => JSON.stringify(String(s));
/** A docstring at `indent`, one line when it fits. */
const docstring = (indent, text) => {
  if (text.length === 0) return null;
  const escaped = text.map((t) => t.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"'));
  return escaped.length === 1 ? `${indent}"""${escaped[0]}"""` : [`${indent}"""${escaped[0]}`, ...escaped.slice(1).map((t) => (t ? `${indent}${t}` : '')), `${indent}"""`];
};

const snake = (name) => name.replace(/-/g, '_').replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const constant = (name) => snake(name).toUpperCase();

const KEYWORDS = new Set(['False', 'None', 'True', 'and', 'as', 'assert', 'async', 'await', 'break', 'class', 'continue', 'def', 'del', 'elif', 'else', 'except', 'finally', 'for', 'from', 'global', 'if', 'import', 'in', 'is', 'lambda', 'nonlocal', 'not', 'or', 'pass', 'raise', 'return', 'try', 'while', 'with', 'yield', 'match', 'case', 'type']);
const ident = (name) => {
  if (!/^[a-z_][a-z0-9_]*$/.test(name)) fail('generate.model', `${JSON.stringify(name)} is not a name the python writer can bind`);
  return KEYWORDS.has(name) ? `${name}_` : name;
};

/** How each scalar WIT type reads in Python. */
const TYPES = Object.freeze({ bool: 'bool', u8: 'int', u16: 'int', u32: 'int', u64: 'int', s8: 'int', s16: 'int', s32: 'int', s64: 'int', f32: 'float', f64: 'float', char: 'int' });
const pyType = (type) => TYPES[type] ?? fail('generate.world', `the python writer has no type for WIT ${type}`);

/** `head` and `items` on one line when it fits in 100 columns, or one item a line, as black lays them out. */
const wrapped = (head, items, open, close) => {
  const line = `${head}${open === '(' ? '' : open}${items.join(', ')}${open === '(' ? '' : close}`;
  return line.length <= 100 ? [line] : [`${head}${open}`, ...items.map((item) => `    ${item},`), close];
};

/** The modules every package holds besides the application's. */
const RESERVED = new Set(['world', 'identity']);

/**
 * The host side of each world, beyond what WIT can say: how a request reaches
 * the guest and how its response comes back. The core-wasm world states it in
 * its file's header comment.
 */
const PROTOCOLS = Object.freeze({
  'hologram:guest/core-wasm@1': [
    'class DispatchError(Exception):',
    '    """A request did not come back from the guest."""',
    '',
    '',
    'def dispatch(guest: Guest, request: bytes) -> bytes:',
    '    """Send one request to a fresh instance of the guest and return a copy of its response.',
    '',
    '    The guest allocator never frees, so give every request its own instance.',
    '    """',
    '    if len(request) > 0xFFFF_FFFF:',
    '        raise DispatchError(f"a request of {len(request)} bytes is too long")',
    '    offset = guest.holo_alloc(len(request))',
    '    guest.write_memory(offset, bytes(request))',
    '    packed = guest.holo_run(offset, len(request))',
    '    # The response location is packed as `offset << 32 | length`.',
    '    return bytes(guest.read_memory(packed >> 32, packed & 0xFFFF_FFFF))',
  ],
});

function identityFile(model) {
  return lines(
    HEADER(`${model.application.name}'s model and the WIT world ${model.world.contract}`),
    '"""What a set of bindings was generated from."""',
    '',
    'from typing import NamedTuple',
    '',
    '',
    'class Identity(NamedTuple):',
    '    """A name and both digests, as prismpm.lock records them."""',
    '',
    '    name: str',
    '    """The world\'s contract, or the application\'s name."""',
    '    blake3: str',
    '    """The BLAKE3 digest, lowercase hex."""',
    '    sha256: str',
    '    """The SHA-256 digest, lowercase hex."""',
  );
}

function worldFile(world) {
  const protocol = PROTOCOLS[world.contract] ?? fail('generate.world', `the python writer has no host protocol for ${world.contract}`);
  if (world.imports.length !== 0) fail('generate.world', `the python writer binds import-free worlds; ${world.contract} has imports`);
  const from = `the WIT world ${world.contract} (${world.file})`;
  const names = [...world.exports.map((f) => f.name), world.memory].sort();
  const methods = world.exports.map((f) => [
    '',
    `    def ${ident(f.name)}(self${f.params.map((p) => `, ${ident(snake(p.name))}: ${pyType(p.type)}`).join('')}) -> ${f.result ? pyType(f.result.type) : 'None'}:`,
    docstring('        ', f.docs.length ? f.docs : [`The export ${f.name}.`]),
    '        ...',
  ]);
  return lines(
    HEADER(from),
    `"""The world ${world.contract}: its identity, its exports, and how a host sends it a request."""`,
    '',
    'from typing import Protocol',
    '',
    'from .identity import Identity',
    '',
    'WORLD = Identity(',
    `    name=${string(world.contract)},`,
    `    blake3=${string(world.digest.blake3)},`,
    `    sha256=${string(world.digest.sha256)},`,
    ')',
    '"""The world these bindings were generated from. It equals `inputs.world` in prismpm.lock."""',
    '',
    `EXPORTS = (${names.map(string).join(', ')})`,
    '"""Every export the world requires, sorted. A guest that offers any other is not of this world."""',
    '',
    '',
    'class Guest(Protocol):',
    `    """A guest of ${world.contract}, instantiated by the host's WebAssembly engine.`,
    '',
    `    The guest imports nothing. Implement this over the engine's instance: each export, and \`${world.memory}\` as a read and a write.`,
    '    A failed call into the guest, such as a trap, raises the engine\'s own exception.',
    '    """',
    methods,
    '',
    '    def write_memory(self, offset: int, data: bytes) -> None:',
    `        """Copy \`data\` into the guest's \`${world.memory}\` at \`offset\`."""`,
    '        ...',
    '',
    '    def read_memory(self, offset: int, length: int) -> bytes:',
    `        """Copy \`length\` bytes out of the guest's \`${world.memory}\` at \`offset\`. Raises when they are outside it."""`,
    '        ...',
    '',
    '',
    protocol,
  );
}

function operationsFile(application) {
  const api = application.interface;
  const { type, errorType, operationType } = { type: application.type, ...api };
  const codeType = `${errorType}Code`;
  const from = `${application.name}'s model (${application.schema}, blake3:${application.model.blake3})`;
  const fallback = {
    'unsupported-version': `${application.name} does not answer request version ${api.version}.`,
    'unknown-operation': `${application.name} does not know this operation.`,
  };
  const variants = api.operations.map((o) => ({ ...o, member: constant(o.name), fn: ident(snake(o.name)) }));
  const errors = api.errors.map((e) => ({ ...e, member: constant(e.code), text: e.message ?? fallback[e.code] }));
  const method = ident(snake(api.method));
  const reserved = new Set([method, 'dispatch']);
  for (const o of variants) if (reserved.has(o.fn) || o.fn.startsWith('_')) fail('generate.model', `operation ${o.name} collides with the method ${o.fn}`);
  if (!errors.some((e) => e.code === 'unsupported-version')) fail('generate.model', `${application.name}'s model has no unsupported-version error`);
  const description = [`A client for ${application.name}.`, ...(application.description ? ['', application.description] : []), '', '`dispatch` sends request bytes to the guest and returns its response bytes, for', 'example `lambda request: world.dispatch(fresh_instance(), request)`.'];
  return lines(
    HEADER(from),
    `"""The client of ${application.name}: one method per operation, over any dispatch function."""`,
    '',
    'from enum import Enum',
    'from typing import Callable, Optional',
    '',
    'from .identity import Identity',
    '',
    'MODEL = Identity(',
    `    name=${string(application.name)},`,
    `    blake3=${string(application.model.blake3)},`,
    `    sha256=${string(application.model.sha256)},`,
    ')',
    '"""The model this client was generated from. It equals `inputs.model` in prismpm.lock."""',
    '',
    `APPLICATION = ${string(application.name)}`,
    `VERSION = ${string(api.version)}`,
    'MINIMUM = -(2**63)',
    'MAXIMUM = 2**63 - 1',
    '',
    '',
    `class ${operationType}(str, Enum):`,
    `    """An operation ${application.name} accepts; its value is the name the guest reads in a request."""`,
    '',
    variants.map((o) => [`    ${o.member} = ${string(o.name)}`, `    """${o.label}."""`]),
    '',
    '',
    `class ${codeType}(str, Enum):`,
    `    """An answer with which ${application.name} refuses a request; its value is the code as the guest wrote it."""`,
    '',
    errors.map((e) => [`    ${e.member} = ${string(e.code)}`, `    """${e.text.replace(/"""/g, '')}"""`]),
    '',
    '    @property',
    '    def message(self) -> str:',
    '        """What the model says this answer means, for a person."""',
    '        return _MESSAGES[self]',
    '',
    '',
    `_MESSAGES = {`,
    errors.map((e) => `    ${codeType}.${e.member}: ${string(e.text)},`),
    '}',
    '',
    '',
    `class ${errorType}(Exception):`,
    `    """${application.name} refused a request, for example on overflow."""`,
    '',
    `    def __init__(self, code: str, known: Optional[${codeType}]) -> None:`,
    `        message = known.message if known is not None else ${string(`${application.name} refused the request.`)}`,
    '        super().__init__(f"{message} ({code})")',
    '        self.code = code',
    '        """The code as the guest wrote it."""',
    '        self.known = known',
    '        """The code, when this client was generated with it; otherwise None."""',
    '        self.message = message',
    '        """What the model says the code means, for a person."""',
    '',
    '',
    'class ResponseError(Exception):',
    `    """${application.name} sent an answer this client cannot read."""`,
    '',
    '',
    `class ${type}:`,
    docstring('    ', description),
    '',
    '    def __init__(self, dispatch: Callable[[bytes], bytes]) -> None:',
    '        """A client over this dispatch function."""',
    '        self._dispatch = dispatch',
    variants.map((o) => [
      '',
      `    def ${o.fn}(self, left: int, right: int) -> int:`,
      `        """${o.label}: \`${method}(${operationType}.${o.member}, left, right)\`."""`,
      `        return self.${method}(${operationType}.${o.member}, left, right)`,
    ]),
    '',
    `    def ${method}(self, operation: ${operationType}, left: int, right: int) -> int:`,
    '        """Apply `operation` to two signed 64-bit integers.',
    '',
    `        A refusal by ${application.name} raises \`${errorType}\`; an operand outside`,
    '        the signed 64-bit range raises ValueError before anything is sent.',
    '        """',
    `        operation = ${operationType}(operation)`,
    '        for operand in (left, right):',
    '            if isinstance(operand, bool) or not isinstance(operand, int):',
    '                raise TypeError(f"{operand!r} is not an int")',
    '            if not MINIMUM <= operand <= MAXIMUM:',
    '                raise ValueError(f"{operand} is outside the signed 64-bit range")',
    '        request = f"{VERSION}\\t{operation.value}\\t{left}\\t{right}"',
    '        return _read(bytes(self._dispatch(request.encode("utf-8"))))',
    '',
    '',
    'def _read(response: bytes) -> int:',
    '    """Read a response: the request version, then `ok` and a value or `error` and a code."""',
    '    try:',
    '        text = response.decode("utf-8")',
    '    except UnicodeDecodeError:',
    '        raise ResponseError("it is not UTF-8") from None',
    '    fields = text.split("\\t")',
    '    if len(fields) > 3:',
    '        raise ResponseError(f"{text!r} has more than three fields")',
    '    if fields[0] != VERSION:',
    `        refused = ${codeType}.UNSUPPORTED_VERSION`,
    `        raise ${errorType}(refused.value, refused)`,
    '    if len(fields) == 3 and fields[1] == "ok":',
    '        value = fields[2]',
    '        if not value.lstrip("-").isdigit() or not MINIMUM <= int(value) <= MAXIMUM:',
    '            raise ResponseError(f"{value!r} is not a signed 64-bit integer")',
    '        return int(value)',
    '    if len(fields) == 3 and fields[1] == "error":',
    `        known = next((code for code in ${codeType} if code.value == fields[2]), None)`,
    `        raise ${errorType}(fields[2], known)`,
    '    raise ResponseError(f"{text!r} is neither ok nor error")',
  );
}

function bytesFile(application) {
  const { type } = application;
  const from = `${application.name}'s model (${application.schema}, blake3:${application.model.blake3})`;
  const description = [`A client for ${application.name}, over request and response bytes.`, ...(application.description ? ['', application.description] : []), '', `${application.name}'s model describes no typed operations, so the client sends bytes.`];
  return lines(
    HEADER(from),
    `"""The client of ${application.name}, over request and response bytes."""`,
    '',
    'from typing import Callable',
    '',
    'from .identity import Identity',
    '',
    'MODEL = Identity(',
    `    name=${string(application.name)},`,
    `    blake3=${string(application.model.blake3)},`,
    `    sha256=${string(application.model.sha256)},`,
    ')',
    '"""The model this client was generated from. It equals `inputs.model` in prismpm.lock."""',
    '',
    '',
    `class ${type}:`,
    docstring('    ', description),
    '',
    '    def __init__(self, dispatch: Callable[[bytes], bytes]) -> None:',
    '        """A client over this dispatch function."""',
    '        self._dispatch = dispatch',
    '',
    '    def invoke(self, request: bytes) -> bytes:',
    '        """Send one request and return the response bytes."""',
    '        return bytes(self._dispatch(bytes(request)))',
  );
}

function initFile(model, module) {
  const { application, world } = model;
  const api = application.interface;
  const names = api.kind === 'operations' ? [application.type, api.operationType, `${api.errorType}Code`, api.errorType, 'ResponseError', 'MODEL'] : [application.type, 'MODEL'];
  // As isort orders names: constants, then classes.
  const sorted = [...names].sort((a, b) => (/^[A-Z0-9_]+$/.test(b) - /^[A-Z0-9_]+$/.test(a)) || (a < b ? -1 : 1));
  return lines(
    HEADER(`${application.name}'s model and the WIT world ${world.contract}`),
    `"""A client for ${application.name}, generated by prism-code generate.`,
    ...(application.description ? ['', application.description] : []),
    '',
    `\`world\` is the world ${world.contract}: implement \`world.Guest\` over your WebAssembly engine,`,
    `and \`world.dispatch\` sends it a request. \`${module}\` is the client of ${application.name}.`,
    '"""',
    '',
    `from . import ${[module, 'world'].sort().join(', ')}`,
    [[`.${module}`, wrapped(`from .${module} import `, sorted, '(', ')')], ['.identity', ['from .identity import Identity']]].sort(([a], [b]) => (a < b ? -1 : 1)).map(([, text]) => text),
    '',
    wrapped('__all__ = ', [...sorted, 'Identity', module, 'world'].sort().map(string), '[', ']'),
  );
}

/** The files of the Python bindings: the package, the world, then the application's client. */
export function write(model) {
  const module = ident(snake(model.application.file));
  if (RESERVED.has(module)) fail('generate.model', `an application named ${module} collides with the ${module} module`);
  const client = model.application.interface.kind === 'operations' ? operationsFile(model.application) : bytesFile(model.application);
  return [
    ['__init__.py', initFile(model, module)],
    ['identity.py', identityFile(model)],
    ['world.py', worldFile(model.world)],
    [`${module}.py`, client],
  ];
}
