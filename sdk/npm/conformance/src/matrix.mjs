/**
 * COMPLIANCE.md: the matrix of feature by runtime, rendered from the suite's
 * reports. A cell is `+` only when every scenario of the feature passed on
 * that runtime, `-` when any did not or the runtime has no report, and `N/A`
 * when the runtime declares the feature not applicable. The file is
 * deterministic: it holds no clock and no path.
 */
import { expandScenarios, loadFeatures, loadScenarios, referenceArchives, PACKAGE_ROOT } from './scenarios.mjs';
import { loadRuntimes } from './runtimes.mjs';
import { validateReport } from './runner.mjs';
import { fail, lf } from './util.mjs';

export const CELLS = Object.freeze({ PASS: '+', FAIL: '-', NOT_APPLICABLE: 'N/A' });
export const HEADER = '<!-- @generated by `prism-conformance matrix` in sdk/npm/conformance from the suite\'s reports. Do not edit; run `npm run matrix` there and commit the result. -->';

const code = (text) => `\`${text}\``;
const escape = (text) => String(text).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

/** The cell of one feature on one runtime. */
export function cellOf(feature, report) {
  if (!report) return CELLS.FAIL;
  const rows = report.scenarios.filter((row) => row.feature === feature);
  if (rows.length === 0) return CELLS.FAIL;
  if (rows.every((row) => row.status === 'not-applicable')) return CELLS.NOT_APPLICABLE;
  return rows.every((row) => row.status === 'passed') ? CELLS.PASS : CELLS.FAIL;
}

function statusOf(id, report) {
  if (!report) return 'no report';
  const row = report.scenarios.find((r) => r.id === id);
  return row ? row.status : 'not run';
}

function summaryOf(report) {
  if (!report) return 'no report: no entrypoint registered';
  const s = report.summary;
  const parts = [`${s.passed} passed`, `${s.failed} failed`];
  if (s.xfail) parts.push(`${s.xfail} expected to fail`);
  if (s['unexpected-pass']) parts.push(`${s['unexpected-pass']} unexpectedly passed`);
  if (s.error) parts.push(`${s.error} errored`);
  if (s['not-applicable']) parts.push(`${s['not-applicable']} not applicable`);
  return parts.join(', ');
}

/**
 * Render the matrix. `reports` maps a runtime name to its report; a runtime
 * registered without one is rendered as having none. A report for a runtime
 * that is not registered is refused.
 */
export function renderMatrix({ root = PACKAGE_ROOT, reports }) {
  const runtimes = loadRuntimes(root);
  const names = Object.keys(runtimes.runtimes);
  for (const name of Object.keys(reports)) {
    if (!names.includes(name)) fail('matrix.runtime', `the report for ${name} names a runtime that runtimes.json does not register`);
    validateReport(reports[name], `the report for ${name}`);
  }
  const features = loadFeatures(root);
  const scenarios = loadScenarios(root, { features });
  const archives = referenceArchives(root);
  const runs = expandScenarios(scenarios, archives);
  const columns = names.map((name) => `${runtimes.runtimes[name].language} (${code(name)})`);
  const out = [];
  out.push(HEADER, '', '# COMPLIANCE', '');
  out.push('The compliance matrix of the Prism runtimes: one row per feature of `@prism-code/conformance`, one column per runtime.');
  out.push('A cell is `+` when every scenario of the feature passed on that runtime in the run that generated this file, `-` when any scenario failed, errored or is an expected failure, or the runtime has no report yet, and `N/A` when the runtime declares the feature not applicable, with its reason below.');
  out.push('Every scenario cites the ids of `CONFORMANCE.md`. Design: `docs/proposals/287-conformance.md`.');
  out.push('');
  out.push(`| Feature | ${columns.join(' | ')} |`);
  out.push(`| --- | ${names.map(() => '---').join(' | ')} |`);
  for (const feature of Object.keys(features.features)) {
    out.push(`| ${code(feature)} | ${names.map((name) => cellOf(feature, reports[name] ?? null)).join(' | ')} |`);
  }
  out.push('', '## Runtimes', '');
  out.push('| Runtime | Language | Version | Result |', '| --- | --- | --- | --- |');
  for (const name of names) {
    const report = reports[name] ?? null;
    const version = report?.runtime.version ? code(report.runtime.version) : '';
    out.push(`| ${code(name)} | ${runtimes.runtimes[name].language} | ${version} | ${escape(summaryOf(report))} |`);
  }
  out.push('', `Reference archives: ${archives.map((archive) => code(archive.name)).join(', ')}.`);
  out.push('', '## Features', '');
  out.push('| Feature | What it covers | Defined by |', '| --- | --- | --- |');
  for (const [name, feature] of Object.entries(features.features)) {
    out.push(`| ${code(name)} | ${escape(feature.title)} | ${feature.definedBy.map(code).join(', ')} |`);
  }
  out.push('', '## Scenarios', '');
  for (const feature of Object.keys(features.features)) {
    out.push(`### ${feature}`, '');
    out.push(`| Scenario | Cites | ${names.map(code).join(' | ')} |`);
    out.push(`| --- | --- | ${names.map(() => '---').join(' | ')} |`);
    for (const run of runs.filter((r) => r.scenario.feature === feature)) {
      out.push(`| ${code(run.id)} | ${run.scenario.cites.map(code).join(', ')} | ${names.map((name) => statusOf(run.id, reports[name] ?? null)).join(' | ')} |`);
    }
    out.push('');
  }
  const declared = [];
  for (const name of names) {
    const report = reports[name];
    if (!report) continue;
    for (const row of report.scenarios) {
      if (row.status === 'xfail' || row.status === 'unexpected-pass') declared.push({ runtime: name, id: row.id, status: row.status, reason: row.reason ?? '' });
    }
  }
  out.push('## Expected failures', '');
  if (declared.length === 0) out.push('None declared.');
  else {
    out.push('| Runtime | Scenario | Status | Reason |', '| --- | --- | --- | --- |');
    for (const item of declared) out.push(`| ${code(item.runtime)} | ${code(item.id)} | ${item.status} | ${escape(item.reason)} |`);
  }
  const notApplicable = [];
  for (const name of names) {
    const report = reports[name];
    if (!report) continue;
    const seen = new Set();
    for (const row of report.scenarios) {
      if (row.status === 'not-applicable' && !seen.has(row.feature)) {
        seen.add(row.feature);
        notApplicable.push({ runtime: name, feature: row.feature, reason: row.reason ?? '' });
      }
    }
  }
  out.push('', '## Not applicable', '');
  if (notApplicable.length === 0) out.push('None declared.');
  else {
    out.push('| Runtime | Feature | Reason |', '| --- | --- | --- |');
    for (const item of notApplicable) out.push(`| ${code(item.runtime)} | ${code(item.feature)} | ${escape(item.reason)} |`);
  }
  out.push('');
  return `${out.join('\n')}`;
}

/** True when `committed` is the rendering, after line endings are normalised. */
export const current = (rendered, committed) => lf(rendered) === lf(committed);
