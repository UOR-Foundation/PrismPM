use super::*;

/// The Calculator fixture `prism-code generate` writes its golden files from.
const CALCULATOR: &[u8] = include_bytes!("../../../../sdk/npm/prism-code/fixtures/Calculator.holo");

fn goldens(directory: &str) -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../sdk/npm/prism-code/test/fixtures/generate")
        .join(directory)
}

/// The files of a directory, LF line ends, without the record.
fn files_of(directory: &Path) -> Vec<(String, String)> {
    let mut files: Vec<(String, String)> = std::fs::read_dir(directory)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
        .filter(|name| name != RECORD)
        .map(|name| {
            let text = std::fs::read_to_string(directory.join(&name))
                .unwrap()
                .replace("\r\n", "\n");
            (name, text)
        })
        .collect();
    files.sort();
    files
}

fn refusal(source: Source) -> (String, String) {
    match write_files(Language::Js, source).unwrap() {
        Written::Refused(code, message) => (code, message),
        Written::Files(files) => panic!("wrote {} files", files.len()),
    }
}

#[test]
fn every_writer_reproduces_the_prism_code_golden_files() {
    for (language, directory) in [
        (Language::Js, "calculator-js"),
        (Language::Python, "calculator-python"),
        (Language::Rust, "calculator-rust"),
    ] {
        let out = tempfile::tempdir().unwrap();
        let generated =
            generate_as(CALCULATOR, language, out.path(), "prism-code generate").unwrap();
        assert_eq!(generated.status, "written");
        assert_eq!(
            files_of(out.path()),
            files_of(&goldens(directory)),
            "{directory}"
        );
        assert_eq!(generated.record["language"], language.name());
        assert_eq!(
            generated.record["world"]["contract"],
            "hologram:guest/core-wasm@1"
        );
    }
}

#[test]
fn regenerating_is_a_no_op_and_repairs_a_changed_file() {
    let out = tempfile::tempdir().unwrap();
    let first = generate(CALCULATOR, Language::Rust, out.path()).unwrap();
    assert_eq!(first.status, "written");
    assert!(first.files.contains(&"calculator.rs".to_owned()));
    let record = std::fs::read(out.path().join(RECORD)).unwrap();

    let second = generate(CALCULATOR, Language::Rust, out.path()).unwrap();
    assert_eq!((second.status, second.files.len()), ("unchanged", 0));
    assert_eq!(std::fs::read(out.path().join(RECORD)).unwrap(), record);

    std::fs::write(out.path().join("world.rs"), "// edited\n").unwrap();
    let repaired = generate(CALCULATOR, Language::Rust, out.path()).unwrap();
    assert_eq!(repaired.files, ["world.rs"]);
    let text = std::fs::read_to_string(out.path().join("world.rs")).unwrap();
    assert!(
        text.starts_with("// Generated by `prismpm generate`"),
        "{text}"
    );
}

#[test]
fn a_file_generate_did_not_write_is_never_replaced() {
    let out = tempfile::tempdir().unwrap();
    std::fs::write(out.path().join("calculator.js"), "mine\n").unwrap();
    let error = generate(CALCULATOR, Language::Js, out.path()).unwrap_err();
    assert_eq!(error.code.as_str(), "PP3202");
    assert_eq!(
        std::fs::read_to_string(out.path().join("calculator.js")).unwrap(),
        "mine\n"
    );
}

