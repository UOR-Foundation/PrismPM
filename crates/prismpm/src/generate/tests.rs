#[test]
fn the_model_refuses_what_it_cannot_bind() {
    let mut source = source(CALCULATOR, GENERATOR).unwrap();
    source.conforms = false;
    let (code, message) = refusal(source);
    assert_eq!(code, "generate.world");
    assert!(message.contains("does not conform"), "{message}");

    let mut source = super::source(CALCULATOR, GENERATOR).unwrap();
    source.wit_blake3 = "0".repeat(64);
    let (_, message) = refusal(source);
    assert!(message.contains("is not the world"), "{message}");

    let mut source = super::source(CALCULATOR, GENERATOR).unwrap();
    source.wit_text = source
        .wit_text
        .replace("func(length: u32)", "func(length: string)");
    let (code, message) = refusal(source);
    assert_eq!(code, "generate.wit");
    assert_eq!(
        message,
        "line 22: type string is outside the scalar subset generate reads"
    );

    let mut source = super::source(CALCULATOR, GENERATOR).unwrap();
    source.wit_text = source
        .wit_text
        .replace("world core-wasm {", "world core-wasm");
    let (_, message) = refusal(source);
    assert_eq!(
        message,
        "line 20: \"world core-wasm\" is outside the WIT subset generate reads"
    );

    let mut source = super::source(CALCULATOR, GENERATOR).unwrap();
    source.world_exports.push("holo_extra".to_owned());
    let (_, message) = refusal(source);
    assert!(
        message.starts_with("the exports of worlds/core-wasm.wit"),
        "{message}"
    );

    let mut source = super::source(CALCULATOR, GENERATOR).unwrap();
    source.operations[1].request_name = "add".to_owned();
    let (code, message) = refusal(source);
    assert_eq!(code, "generate.model");
    assert_eq!(message, "operation add collides with the method add");

    let mut source = super::source(CALCULATOR, GENERATOR).unwrap();
    source.application_name = Some("9lives".to_owned());
    let (_, message) = refusal(source);
    assert!(
        message.contains("is not one generate can turn into a class name"),
        "{message}"
    );
}

#[test]
fn a_model_without_the_numeric_profile_gets_a_client_over_bytes() {
    let mut source = source(CALCULATOR, GENERATOR).unwrap();
    source.input_grammar = "Utf8Text".to_owned();
    let Written::Files(files) = write_files(Language::Rust, source).unwrap() else {
        panic!("refused")
    };
    let client = &files
        .iter()
        .find(|(name, _)| name == "calculator.rs")
        .unwrap()
        .1;
    assert!(!client.contains("Operation"), "{client}");
}
