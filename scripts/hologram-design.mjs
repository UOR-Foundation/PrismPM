#!/usr/bin/env node
// Generates the source-bound Hologram design catalogue and the WCAG luminance
// table from first principles, and checks the committed sources against them.
//
//   node scripts/hologram-design.mjs --check
//   node scripts/hologram-design.mjs --write --tokens <hologram-tokens.json> --revision <kit commit>
//
// The tokens file is brand/tokens/hologram-tokens.json of
// Hologram-Technologies/hologram-brand-kit. --check needs no kit checkout: it
// re-derives the table and re-checks the committed catalogue's contrast with
// the same integer rule the Lean source states, so the two cannot drift.
import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DESIGN = 'stdlib/src/Foundation/View/Browser/V1/Design.lex.tex';
const HOLOGRAM = 'stdlib/src/Foundation/View/Browser/V1/HologramDesign.lex.tex';

// The contrast rule and token order are the SDK's own, so the Lean source, the
// browser decoder and this generator state one rule.
import {SCALE, ERROR, OFFSET, linear, TABLE, luminance, contrastAtLeast, FIELDS, PAIRS, tokensContrastValid}
  from '../sdk/browser/design-contrast.mjs';
export {SCALE, ERROR, OFFSET, linear, TABLE, luminance, contrastAtLeast, FIELDS, PAIRS, tokensContrastValid};
export const EXTENDED = Object.freeze(FIELDS.slice(16));
export const COLORS = Object.freeze(FIELDS.slice(0, 7));

// Kit token -> catalogue field. Dark borders and inputs are translucent in the
// kit, so the catalogue takes the kit's opaque solid and strong borders.
const KIT = Object.freeze({surface: 'background', text: 'foreground', border: 'border-solid', accent: 'primary',
  accentText: 'primary-foreground', danger: 'destructive', focus: 'ring', card: 'card', muted: 'muted',
  mutedText: 'muted-foreground', hover: 'accent', input: 'border-strong', brand: 'brand', brandText: 'brand-text',
  success: 'success', warning: 'warning'});
// Non-colour tokens: Hologram fonts, 1rem text, 1.5 line height, 1.5rem
// space, 0.625rem radius, 82rem content, 16rem sidebar, 50rem collapse, 40px targets.
const METRICS = Object.freeze({fontFamily: 'Hologram', textPermille: 1000, lineHeightPermille: 1500,
  spacePermille: 1500, radiusPermille: 625, contentWidthRem: 82, sidebarWidthRem: 16, collapseWidthRem: 50,
  targetPixels: 40});

const hex = color => '0x' + color.toString(16).padStart(6, '0');
function kitTokens(path, set) {
  const tokens = JSON.parse(readFileSync(path, 'utf8'))[set]?.color;
  assert(tokens, `kit token set ${set} is missing`);
  return Object.fromEntries(Object.entries(KIT).map(([field, name]) => {
    const value = tokens[name]?.$value;
    assert(/^#[0-9a-f]{6}$/.test(value ?? ''), `${set}.${name} must be an opaque #rrggbb colour, got ${value}`);
    return [field, Number.parseInt(value.slice(1), 16)];
  }));
}
function record(colors) {
  const fields = FIELDS.map(field => {
    if (field === 'fontFamily') return `fontFamily := (ctor Foundation.View.Browser.V1.Design::FontFamily.${METRICS.fontFamily})`;
    if (field in METRICS) return `${field} := ${METRICS[field]}`;
    return `${field} := ${colors[field]}`;
  });
  return `(record Foundation.View.Browser.V1.Design::DesignTokens {${fields.join(', ')}})`;
}
export function tokenArray(colors) {
  return FIELDS.map(field => field === 'fontFamily' ? 3 : field in METRICS ? METRICS[field] : colors[field]);
}
function hologramSource(light, dark, revision) {
  return `\\begin{lexlean}{Foundation.View.Browser.V1.HologramDesign}
\\useglossary{lexlean.std.bool@1.2.0}
\\useglossary{lexlean.std.nat@1.2.0}
\\useglossary{prism.arch@1.0.0}
\\importmodule{Foundation.View.Browser.V1.Design}
\\title{Browser view design catalogue}
\\begin{semanticmodule}
definition{
  name: hologramDesignSource,
  parameters: [],
  result: String,
  body: "Generated by scripts/hologram-design.mjs from Hologram-Technologies/hologram-brand-kit brand/tokens/hologram-tokens.json at ${revision}",
  axioms: []
}

definition{
  name: hologramDesignPair,
  parameters: [],
  result: Foundation.View.Browser.V1.Design::DesignPair,
  body: (record Foundation.View.Browser.V1.Design::DesignPair {light := ${record(light)}, dark := ${record(dark)}}),
  axioms: []
}

definition{
  name: hologramDesignCatalogue,
  parameters: [],
  result: (List Foundation.View.Browser.V1.Design::DesignPair),
  body: (cons (hologramDesignPair) (nil Foundation.View.Browser.V1.Design::DesignPair)),
  axioms: []
}

theorem{
  name: hologramDesignCatalogueValid,
  parameters: [],
  statement: ((Foundation.View.Browser.V1.Design::designCatalogueAdmitted (hologramDesignCatalogue)) = true),
  proof: decide{},
  axioms: []
}
\\end{semanticmodule}
\\end{lexlean}
`;
}

// The table as LexLean: sixteen rows of sixteen, selected by row then column.
export function tableSource() {
  const rows = Array.from({length: 16}, (_, row) => TABLE.slice(row * 16, row * 16 + 16));
  const list = values => values.reduceRight((tail, value) => `(cons ${value} ${tail})`, '(nil Nat)');
  const select = rows.reduceRight((otherwise, values, row) =>
    row === 15 ? list(values) : `(if (row =? ${row}) then ${list(values)} else ${otherwise})`, '');
  return `definition{
  name: designLinearRow,
  parameters: [row : Nat],
  result: (List Nat),
  body: ${select},
  axioms: []
}`;
}

function committedTable() {
  const source = readFileSync(join(root, DESIGN), 'utf8');
  const start = source.indexOf('definition{\n  name: designLinearRow,');
  assert(start >= 0, `${DESIGN} has no designLinearRow definition`);
  return source.slice(start, source.indexOf('\n}', start) + 2);
}
function committedHologram() {
  const source = readFileSync(join(root, HOLOGRAM), 'utf8');
  const pair = name => {
    const match = new RegExp(`${name} := \\(record Foundation\\.View\\.Browser\\.V1\\.Design::DesignTokens \\{([^}]*)\\}`).exec(source);
    assert(match, `${HOLOGRAM} has no ${name} tokens`);
    const values = Object.fromEntries(match[1].split(', ').map(item => item.split(' := ')));
    return FIELDS.map(field => field === 'fontFamily' ? 3 : Number(values[field]));
  };
  return {light: pair('light'), dark: pair('dark')};
}

export function check() {
  assert.equal(committedTable(), tableSource(), `${DESIGN} luminance table differs from the WCAG formula`);
  for (const [value, entry] of TABLE.entries()) assert(Math.abs(entry - linear(value) * SCALE) <= 0.5);
  const {light, dark} = committedHologram();
  for (const [name, tokens] of Object.entries({light, dark})) {
    const failing = PAIRS.filter(([fg, bg, n, d]) => !contrastAtLeast(tokens[FIELDS.indexOf(fg)], tokens[FIELDS.indexOf(bg)], n, d));
    assert.deepEqual(failing, [], `hologram ${name} fails contrast: ${failing.map(pair => pair.slice(0, 2).join(' on ')).join(', ')}`);
  }
  return {table: TABLE.length, pairs: PAIRS.length * 2};
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const option = name => { const index = args.indexOf(name); return index >= 0 ? args[index + 1] : undefined; };
  if (args.includes('--write')) {
    const tokens = option('--tokens'), revision = option('--revision');
    assert(tokens && /^[0-9a-f]{7,40}$/.test(revision ?? ''), 'usage: --write --tokens <hologram-tokens.json> --revision <kit commit>');
    const light = kitTokens(tokens, 'hologram-light'), dark = kitTokens(tokens, 'hologram-dark');
    writeFileSync(join(root, HOLOGRAM), hologramSource(light, dark, revision));
    console.log(`wrote ${HOLOGRAM} from kit ${revision}`);
    console.log(tableSource());
  } else {
    const result = check();
    console.log(`hologram-design: ${result.table}-entry table matches WCAG, ${result.pairs}/${result.pairs} catalogue pairs pass`);
  }
}
